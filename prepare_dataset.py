#!/usr/bin/env python3
"""Turn a downloaded public waste-image dataset (one folder per class) into EcoSort evaluation files.

Public datasets label by MATERIAL (glass, paper, battery ...), one object per photo. EcoSort uses the
Indian categories (wet / dry / domestic_hazardous / e_waste / sanitary). This script maps the classes,
samples a balanced set of photos, copies them to eval_data/images and writes eval_data/labels_public.csv.
Rows use item name "*" = "single object, judge the category only" (run_eval.py understands this).

Usage (project root):
    python evaluation/prepare_dataset.py --source "C:/data/garbage-classification-v2" --per-category 30
"""
import argparse
import csv
import math
import random
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
IMG_EXT = {".jpg", ".jpeg", ".png", ".webp"}

# public-dataset class -> EcoSort category (classes not listed are ignored)
CLASS_MAP = {
    "biological": "wet", "organic": "wet", "food-waste": "wet",
    "battery": "domestic_hazardous", "batteries": "domestic_hazardous",
    "cardboard": "dry", "paper": "dry", "plastic": "dry", "metal": "dry",
    "glass": "dry", "green-glass": "dry", "brown-glass": "dry", "white-glass": "dry",
    "clothes": "dry", "shoes": "dry", "textile": "dry",
}
OPTIONAL = {"trash": "dry"}   # general 'trash' is ambiguous; only used with --include-trash


def norm(name):
    return name.lower().strip().replace("_", "-").replace(" ", "-")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", required=True, help="folder of the downloaded dataset (contains one folder per class)")
    ap.add_argument("--per-category", type=int, default=30, help="photos to sample for each EcoSort category")
    ap.add_argument("--include-trash", action="store_true", help="also use the ambiguous 'trash' class as dry waste")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--images-out", default=str(HERE / "eval_data" / "images"))
    ap.add_argument("--labels-out", default=str(HERE / "eval_data" / "labels_public.csv"))
    args = ap.parse_args()

    src = Path(args.source)
    if not src.is_dir():
        raise SystemExit(f"Source folder not found: {src}")
    mapping = dict(CLASS_MAP, **(OPTIONAL if args.include_trash else {}))

    # every folder that directly contains images counts as a class (works for train/test sub-folders too)
    found = {}
    for d in [src] + [p for p in src.rglob("*") if p.is_dir()]:
        files = [f for f in d.iterdir() if f.is_file() and f.suffix.lower() in IMG_EXT]
        if files:
            found.setdefault(norm(d.name), []).extend(files)
    if not found:
        raise SystemExit("No images found. Point --source at the unzipped dataset folder.")

    ignored = sorted(c for c in found if c not in mapping)
    by_cat = {}
    for cls, files in found.items():
        if cls in mapping:
            by_cat.setdefault(mapping[cls], {})[cls] = files

    rng = random.Random(args.seed)
    out_img = Path(args.images_out)
    out_img.mkdir(parents=True, exist_ok=True)
    rows, counts = [], {}
    for cat, classes in by_cat.items():
        quota = math.ceil(args.per_category / len(classes))
        picked = []
        for cls, files in sorted(classes.items()):
            for f in rng.sample(files, min(quota, len(files))):
                picked.append((cls, f))
        rng.shuffle(picked)
        for i, (cls, f) in enumerate(picked[: args.per_category]):
            name = f"pub_{cat}_{cls}_{i:03d}{f.suffix.lower()}"
            shutil.copy2(f, out_img / name)
            rows.append([name, "*", cat, "1" if cat == "domestic_hazardous" else "0", "", "Not sure"])
        counts[cat] = min(len(picked), args.per_category)

    with open(args.labels_out, "w", newline="", encoding="utf-8") as fh:
        fh.write("# Generated by prepare_dataset.py - single-object photos from a public dataset (item '*' = judge category only)\n")
        w = csv.writer(fh)
        w.writerow(["image", "items", "categories", "hazards", "batch", "answer"])
        w.writerows(rows)

    print(f"Copied {len(rows)} photos to {out_img}")
    for cat, n in counts.items():
        print(f"  {cat:20s} {n}")
    print(f"Labels written to {args.labels_out}")
    if ignored:
        print("Ignored classes (no EcoSort mapping):", ", ".join(ignored))
    missing = [c for c in ("wet", "dry", "domestic_hazardous", "e_waste", "sanitary") if c not in counts]
    if missing:
        print("NOT covered by this dataset - take your own photos for:", ", ".join(missing))


if __name__ == "__main__":
    main()
